    // Clips to the side of the line through p, normal to t, that t points to (s = 1) or from (s = -1).
    function halfPlane(c, p, t, s) {
      var L = 3000, nx = -t[1] * L, ny = t[0] * L, fx = s * t[0] * L, fy = s * t[1] * L;
      c.beginPath(); c.moveTo(p[0] + nx, p[1] + ny); c.lineTo(p[0] - nx, p[1] - ny);
      c.lineTo(p[0] - nx + fx, p[1] - ny + fy); c.lineTo(p[0] + nx + fx, p[1] + ny + fy); c.closePath(); c.clip();
    }
