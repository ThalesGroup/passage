    function at(x, y) { return "translate3d(" + px(x) + "," + px(y) + ",0)"; }

    // Least-cost paths across the map (distance, elevation, climb, reading areas
    // and obstacles), computed with A* at idle moments.
    function pickEnd() {
      for (var tries = 0; tries < 300; tries++) {
        var i = 2 + Math.floor(Math.random() * (NX - 4)), j = 2 + Math.floor(Math.random() * (NY - 4)), n = j * NX + i;
        if (elev[n] < 0.42 && !calmMask[n] && !obsCost[n]) return n;
      }
      return -1;
    }
    function mapStep(n, m, len) {
      if (obsMask[m]) return Infinity;
      var en = elev[n], em = elev[m];
      return len * (0.6 + 7 * (en + em) / 2 + calmCost[m] + obsCost[m]) + 60 * Math.max(0, em - en);
    }
    // From the grid path to a clean curve: straighten it where a direct line costs
    // no more, then draw a B-spline near it; with control points further apart the
    // curve is calmer, closer apart it follows tighter bends. The calmest curve
    // that keeps clear of the reading areas and obstacles wins.
    function curveOf(poly, lead) {
      for (var D = 56; D >= 8; D -= 12) {
        var curve = D > 8 ? resample(bspline(lead ? lead.concat(poly) : poly, D), 3) : resample(lead ? lead.concat(poly) : poly, 3);
        if (lead) {
          // A detour: start exactly on the joint, the small offset fading out over 40 px.
          var p = poly[0], i0 = 0, best = Infinity, k, acc = 0;
          for (k = 0; k < curve.length; k++) { var d = Math.hypot(curve[k][0] - p[0], curve[k][1] - p[1]); if (d < best) { best = d; i0 = k; } }
          curve = curve.slice(i0);
          var dx = p[0] - curve[0][0], dy = p[1] - curve[0][1];
          for (k = 0; k < curve.length; k++) {
            if (k) acc += Math.hypot(curve[k][0] - curve[k - 1][0], curve[k][1] - curve[k - 1][1]);
            var w = Math.max(0, 1 - acc / 40); w = w * w * (3 - 2 * w);
            curve[k] = [curve[k][0] + dx * w, curve[k][1] + dy * w];
          }
        }
        if (clear(curve)) return curve;
      }
      return null;
    }
    function makeRoute() {
      var s = -1, g = -1, diag = Math.hypot(NX, NY);
      for (var tries = 0; tries < 40; tries++) {
        s = pickEnd(); g = pickEnd();
        if (s < 0 || g < 0) return null;
        var sx = s % NX, sy = (s / NX) | 0, gx = g % NX, gy = (g / NX) | 0, hit = 0;
        if (Math.hypot(sx - gx, sy - gy) < diag * 0.4) continue;
        for (var q = 1; q < 20; q++) hit += calmMask[Math.round(sy + (gy - sy) * q / 20) * NX + Math.round(sx + (gx - sx) * q / 20)];
        if (hit <= 3 || tries > 30) break;
      }
      var path = astar(mapStep, s, g, 0.6);
      if (!path) return null;
      var curve = curveOf(pull(path).map(nodePx), null);
      return curve ? measured(curve) : null;
    }
    // Step cost along a straight line between two nodes, as mapStep counts it;
    // Infinity if the line enters a reading area or an obstacle.
    function lineCost(a, b) {
      var ax = a % NX, ay = (a / NX) | 0, bx = b % NX, by = (b / NX) | 0, len = Math.hypot(bx - ax, by - ay);
      var steps = Math.max(1, Math.ceil(len * 2)), ds = len / steps, sum = 0, prev = elev[a];
      for (var q = 1; q <= steps; q++) {
        var x = ax + (bx - ax) * q / steps, y = ay + (by - ay) * q / steps, i = Math.min(NX - 2, x | 0), j = Math.min(NY - 2, y | 0);
        var fx = x - i, fy = y - j, k = j * NX + i, nn = Math.round(y) * NX + Math.round(x), e, cc;
        if (calmMask[nn] || obsMask[nn]) return Infinity;
        e = (elev[k] * (1 - fx) + elev[k + 1] * fx) * (1 - fy) + (elev[k + NX] * (1 - fx) + elev[k + NX + 1] * fx) * fy;
        cc = (calmCost[k] * (1 - fx) + calmCost[k + 1] * fx) * (1 - fy) + (calmCost[k + NX] * (1 - fx) + calmCost[k + NX + 1] * fx) * fy;
        sum += ds * (0.6 + 7 * (prev + e) / 2 + cc + obsCost[nn]) + 60 * Math.max(0, e - prev);
        prev = e;
      }
      return sum;
    }
    // Keeps the nodes where the path must turn: from each kept node, the furthest
    // later node, within a few cells, that a straight line reaches for no more
    // cost. Short reaches keep the meanders of the valleys.
    function pull(path) {
      var n = path.length, cum = [0], out = [path[0]], i = 0, k;
      for (k = 1; k < n; k++) {
        var a = path[k - 1], b = path[k];
        cum.push(cum[k - 1] + mapStep(a, b, a % NX !== b % NX && ((a / NX) | 0) !== ((b / NX) | 0) ? 1.41421356 : 1));
      }
      while (i < n - 1) {
        var best = i + 1, miss = 0;
        for (var j = i + 2; j < n && j - i <= 28; j++) {
          if (lineCost(path[i], path[j]) <= (cum[j] - cum[i]) * 1.005) { best = j; miss = 0; }
          else if (++miss > 5) break;
        }
        out.push(path[best]); i = best;
      }
      return out;
    }
    function clear(pts) {
      for (var k = 0; k < pts.length; k++) { var n = nodeAt(pts[k]); if (calmMask[n] || obsMask[n]) return false; }
      return true;
    }
    // First index of the route inside an obstacle's blocked zone, or -1.
    function hitAt(r) {
      for (var k = 0; k < r.pts.length; k += 2) if (obsMask[nodeAt(r.pts[k])]) return k;
      return -1;
    }
    // Routes keep apart: the nodes near the living routes are marked, and a new
    // route may share only a little of them.
    function mark(r, s) {
      for (var k = 0; k < r.pts.length; k += 3) {
        var i0 = Math.round(r.pts[k][0] / C), j0 = Math.round(r.pts[k][1] / C);
        for (var j = Math.max(0, j0 - 2); j <= Math.min(NY - 1, j0 + 2); j++) for (var i = Math.max(0, i0 - 2); i <= Math.min(NX - 1, i0 + 2); i++) {
          var q = j * NX + i; occ[q] = Math.max(0, occ[q] + s);
        }
      }
    }
    function overlap(r) {
      var hit = 0, n = 0;
      for (var k = 0; k < r.pts.length; k += 3, n++) if (occ[nodeAt(r.pts[k])]) hit++;
      return hit / Math.max(1, n);
    }
    function fillPool(target) {
      idleId = 0;
      if (destroyed || !elev) return;
      var my = gen;
      if (pool.length < target) { var r = makeRoute(); if (r) pool.push(r); }
      if (pool.length < target) idleId = idle(function () { if (my === gen) fillPool(target); }, { timeout: 600 });
    }
    function refill() { if (ready && !idleId && pool.length < nRoutes() + 3) idleId = idle(function () { fillPool(nRoutes() + 3); }, { timeout: 600 }); }
    function pickRoute() {
      pool = pool.filter(function (r) { return used.indexOf(r) >= 0 || hitAt(r) < 0; });
      refill();
      var free = pool.filter(function (r) { return used.indexOf(r) < 0 && overlap(r) < 0.2; });
      return free.length ? free[Math.floor(Math.random() * free.length)] : null;
    }

    // ----------------------------------------------------------- obstacles
    // No-go zones shaped like the benchmark's obstacles: rotated super-ellipses,
    // hatched, inside a dashed keep-out margin. One appears with a sonar ping, a
    // lock-on flash and a body that settles into place, stays still while it
    // lives, then dissolves. Routes are planned around the obstacles, and a
    // living route that a new one cuts replans: its blocked part dissolves and a
    // detour grows around the zone.
    var obstacles = [], obsMask = null, obsCost = null, KEEP = 9, NEAR = 30;   // px: blocked margin, then a costlier band
    function superPath(c, ob, grow) {
      var a = ob.a + grow, b = ob.b + grow, cs = Math.cos(ob.rot), sn = Math.sin(ob.rot), q = 2 / ob.n;
      c.beginPath();
      for (var i = 0; i < 96; i++) {
        var t = i / 96 * TAU, ct = Math.cos(t), st = Math.sin(t);
        var x = a * (ct < 0 ? -1 : 1) * Math.pow(Math.abs(ct), q), y = b * (st < 0 ? -1 : 1) * Math.pow(Math.abs(st), q);
        var X = ob.cx + x * cs - y * sn, Y = ob.cy + x * sn + y * cs;
        if (i) c.lineTo(X, Y); else c.moveTo(X, Y);
      }
      c.closePath();
    }
    // <= 1 inside the shape grown by grow px.
    function inside(ob, x, y, grow) {
      var dx = x - ob.cx, dy = y - ob.cy, cs = Math.cos(ob.rot), sn = Math.sin(ob.rot);
      return Math.pow(Math.abs((dx * cs + dy * sn) / (ob.a + grow)), ob.n) + Math.pow(Math.abs((-dx * sn + dy * cs) / (ob.b + grow)), ob.n);
    }
    function rasterise(ob, sign) {
      var R = Math.max(ob.a, ob.b) + KEEP + NEAR, i0 = Math.max(0, Math.floor((ob.cx - R) / C)), i1 = Math.min(NX - 1, Math.ceil((ob.cx + R) / C));
      var j0 = Math.max(0, Math.floor((ob.cy - R) / C)), j1 = Math.min(NY - 1, Math.ceil((ob.cy + R) / C));
      for (var j = j0; j <= j1; j++) for (var i = i0; i <= i1; i++) {
        var k = j * NX + i;
        if (inside(ob, i * C, j * C, KEEP) <= 1) obsMask[k] = Math.max(0, obsMask[k] + sign);
        var q = inside(ob, i * C, j * C, KEEP + NEAR);
        if (q <= 1) obsCost[k] = Math.max(0, obsCost[k] + sign * 6 * (1 - q));
        if (obsCost[k] < 1e-4) obsCost[k] = 0;
      }
    }
    function cuts(ob, r) {
      for (var k = 0; k < r.pts.length; k += 2) if (inside(ob, r.pts[k][0], r.pts[k][1], KEEP + 4) <= 1) return true;
      return false;
    }
    function shape(cx, cy) { var s = small ? 0.75 : 1; return { cx: cx, cy: cy, a: s * rnd(30, 52), b: s * rnd(22, 38), n: rnd(2.4, 4.2), rot: rnd(0, Math.PI) }; }
    // Room for an obstacle: inside the map, away from the reading areas, the other
    // obstacles and the ends of the living routes; it may cut only routes that are
    // fully drawn (they replan).
    function fits(ob) {
      var R = Math.max(ob.a, ob.b) + KEEP, k;
      if (ob.cx - R < 12 || ob.cy - R < 12 || ob.cx + R > W - 12 || ob.cy + R > H - 12) return false;
      var i0 = Math.max(0, Math.floor((ob.cx - R - 16) / C)), i1 = Math.min(NX - 1, Math.ceil((ob.cx + R + 16) / C));
      var j0 = Math.max(0, Math.floor((ob.cy - R - 16) / C)), j1 = Math.min(NY - 1, Math.ceil((ob.cy + R + 16) / C));
      for (var j = j0; j <= j1; j++) for (var i = i0; i <= i1; i++) if (calmMask[j * NX + i] && inside(ob, i * C, j * C, KEEP + 16) <= 1) return false;
      for (k = 0; k < obstacles.length; k++) {
        var q = obstacles[k];
        if (Math.hypot(q.cx - ob.cx, q.cy - ob.cy) < R + Math.max(q.a, q.b) + KEEP + 40) return false;
      }
      for (k = 0; k < lives.length; k++) {
        var L = lives[k], s = L.r.pts[0], e = L.r.pts[L.r.pts.length - 1];
        if (inside(ob, s[0], s[1], KEEP + 26) <= 1 || inside(ob, e[0], e[1], KEEP + 26) <= 1) return false;
        if (L.phase !== "live" && cuts(ob, L.r)) return false;
      }
      return true;
    }
    function obCanvas(ob, g, grow, draw) {
      var R = Math.max(ob.a, ob.b) + grow + 6, Lc = layerCanvas({ x: Math.floor(ob.cx - R), y: Math.floor(ob.cy - R), w: Math.ceil(2 * R), h: Math.ceil(2 * R) }, g.el);
      draw(Lc.c);
      return Lc.cv;
    }
    function drawObstacle(ob) {
      var T = theme(), g = Group();
      ob.g = g;
      ob.body = obCanvas(ob, g, 4, function (c) {
        var R = Math.max(ob.a, ob.b) + 4;
        superPath(c, ob, 0); c.fillStyle = T.obFill; c.fill();
        c.save(); c.clip(); c.strokeStyle = T.obHatch; c.lineWidth = 1; c.beginPath();
        for (var d = -2 * R; d <= 2 * R; d += 6) { c.moveTo(ob.cx + d - R, ob.cy - R); c.lineTo(ob.cx + d + R, ob.cy + R); }
        c.stroke(); c.restore();
        superPath(c, ob, 0);
        c.globalCompositeOperation = T.add; c.strokeStyle = rgba(T.obLine, 0.3); c.lineWidth = 5; c.stroke();
        c.globalCompositeOperation = "source-over"; c.strokeStyle = rgba(T.obLine, 0.95); c.lineWidth = 1.4; c.stroke();
      });
      ob.rim = obCanvas(ob, g, KEEP + 2, function (c) {
        superPath(c, ob, KEEP); c.setLineDash([3, 5]); c.strokeStyle = rgba(T.obLine, 0.75); c.lineWidth = 1; c.stroke();
      });
      return g;
    }
    function addObstacle(ob, animate) {
      obstacles.push(ob); rasterise(ob, 1);
      var g = drawObstacle(ob), T = theme();
      pool = pool.filter(function (r) { return used.indexOf(r) >= 0 || hitAt(r) < 0; });
      if (!animate) return;
      // Sonar ping, lock-on flash, then the body settles with a slight overshoot and
      // the margin closes in. No delays: each layer's animation starts now and
      // waits through its first keyframes, so the arrival wakes the main thread
      // once. Between its arrival and its departure an obstacle stays still: a
      // layer animated without end would be redrawn on every frame without a GPU.
      var S = 2 * (Math.max(ob.a, ob.b) + KEEP), out = "cubic-bezier(0.2, 0.7, 0.3, 1)", pings = [];
      for (var i = 0; i < 2; i++) {
        var ping = el("div", "na-ping", g.el), d = i * 320, T1 = 1300 + d;
        ping.style.setProperty("--c", T.obLine.join(","));
        ping.style.width = ping.style.height = px(S); ping.style.left = px(ob.cx - S / 2); ping.style.top = px(ob.cy - S / 2);
        play(g, ping, [{ transform: "scale(0.2)", opacity: 0, offset: 0 }, { transform: "scale(0.2)", opacity: 0.9, offset: d / T1, easing: out }, { transform: "scale(1.45)", opacity: 0, offset: 1 }], { duration: T1 });
        pings.push(ping);
      }
      later(function () { pings.forEach(function (e) { e.remove(); }); }, 1700);
      var flash = obCanvas(ob, g, 4, function (c) { superPath(c, ob, 0); c.fillStyle = rgba(T.obFlash, 0.9); c.fill(); });
      flash.style.opacity = "0";
      play(g, flash, [{ opacity: 0, transform: "scale(1.18)", offset: 0 }, { opacity: 0, transform: "scale(1.18)", offset: 0.36, easing: "ease-out" },
        { opacity: 0.6, transform: "scale(1.02)", offset: 0.58, easing: "ease-out" }, { opacity: 0, transform: "scale(1)", offset: 1 }], { duration: 1180 });
      play(g, ob.body, [{ opacity: 0, transform: "scale(0.55)", offset: 0 }, { opacity: 0, transform: "scale(0.55)", offset: 0.32, easing: "cubic-bezier(0.2, 0.8, 0.3, 1)" },
        { opacity: 1, transform: "scale(1.07)", offset: 0.73, easing: "ease-in-out" }, { opacity: 1, transform: "scale(1)", offset: 1 }], { duration: 1320 });
      ob.rim.style.opacity = "0.8";
      play(g, ob.rim, [{ opacity: 0, transform: "scale(1.3)", offset: 0 }, { opacity: 0, transform: "scale(1.3)", offset: 0.6, easing: "ease-out" }, { opacity: 0.8, transform: "scale(1)", offset: 1 }], { duration: 1500 });
      later(function () { removeObstacle(ob); }, rnd(15000, 23000));
      // The living routes that it cuts replan once it has locked on.
      later(function () {
        lives.slice().forEach(function (L) { if (L.phase === "live" && hitAt(L.r) >= 0) replan(L); });
      }, 700);
    }
    function removeObstacle(ob) {
      if (obstacles.indexOf(ob) < 0 || ob.leaving) return;
      ob.leaving = true;
      play(ob.g, ob.body, [{ opacity: 1, transform: "scale(1)" }, { opacity: 0, transform: "scale(0.9)" }], { duration: 800, easing: "ease-in", fill: "forwards" });
      play(ob.g, ob.rim, [{ opacity: 0.8, transform: "scale(1)" }, { opacity: 0, transform: "scale(1.22)" }], { duration: 700, easing: "ease-out", fill: "forwards" });
      later(function () { if (obstacles.indexOf(ob) < 0) return; done(ob.g); rasterise(ob, -1); drop(obstacles, ob); }, 850);
    }
    function spawnObstacle() {
      if (!running()) { later(spawnObstacle, 1500); return; }
      if (obstacles.length < (small ? 1 : 3)) {
        var ob = null, now = performance.now(), t, live = lives.filter(function (L) { return L.phase === "live" && !L.replanned && L.liveEnd - now > 5500; });
        // Most often across a living route, between its first and last thirds.
        if (live.length && Math.random() < 0.75) {
          var L = live[Math.floor(Math.random() * live.length)];
          for (t = 0; t < 10 && !ob; t++) {
            var p = L.r.pts[Math.round((L.r.pts.length - 1) * rnd(0.36, 0.64))], c1 = shape(p[0] + rnd(-10, 10), p[1] + rnd(-10, 10));
            if (fits(c1)) ob = c1;
          }
        }
        for (t = 0; t < 20 && !ob; t++) {
          var c2 = shape(rnd(40, W - 40), rnd(40, H - 40));
          if (fits(c2) && !lives.some(function (Q) { return cuts(c2, Q.r); })) ob = c2;
        }
        if (ob) addObstacle(ob, true);
      }
      later(spawnObstacle, rnd(4500, 8000));
    }

    // ---------------------------------------------------------- route lives
    // A life: the route appears behind a travelling light, a light point runs from
    // start to goal while the goal pulses, then a last light erases it. An obstacle
    // may make it replan on the way.
    function lifeLater(L, fn, ms) { var tk = L.token; later(function () { if (tk === L.token) fn(); }, ms); }
    // Opacity of pieces over one phase of T ms: each goes to `to` between its own
    // times a and b (ms). Every piece gets one animation, all starting together and
    // lasting the whole phase, so a phase wakes the main thread only at its start
    // and its end (a delayed animation would wake it at its own start and end).
    // The inline style keeps the end value.
    function phase(list, to, T) {
      list.forEach(function (it) {
        var P = it.P, from = +P.cv.style.opacity || 0, a = clamp(it.a / T, 0, 1), b = clamp(it.b / T, a, 1);
        if (P.an) P.an.cancel();
        P.cv.style.opacity = String(to);
        if (P.cv.animate) P.an = P.cv.animate([{ opacity: from, offset: 0 }, { opacity: from, offset: a }, { opacity: to, offset: b }, { opacity: to, offset: 1 }], { duration: T, easing: "linear" });
      });
    }
    function buildPieces(L, r, kA, kB, t0) {
      var out = [];
      piecesRange(r, kA, kB, clamp(Math.round((r.cum[kB] - r.cum[kA]) / 100), 2, 10)).forEach(function (cu, idx) {
        var Lc = layerCanvas(bboxPts(r.pts, cu[0], cu[1], 14), L.g.el);
        strokeRoute(Lc.c, r, cu[0], cu[1], L.col, idx === 0 ? t0 : null);
        endpoints(Lc.c, r, L.col, cu[0] === 0, cu[1] === r.pts.length - 1);
        Lc.cv.style.opacity = "0";
        out.push({ cv: Lc.cv, k0: cu[0], k1: cu[1], an: null });
      });
      return out;
    }
    // Pieces from index pi0 on appear as a light runs over them, then `then`.
    function reveal(L, pi0, then) {
      var r = L.r, kA = L.pieces[pi0].k0, kB = r.pts.length - 1, span = Math.max(1, r.cum[kB] - r.cum[kA]);
      var REV = clamp(span / 0.38, 900, 3600), lt = light(L.g.el, L.col), list = [];
      for (var i = pi0; i < L.pieces.length; i++) {
        var P = L.pieces[i], f0 = (r.cum[P.k0] - r.cum[kA]) / span, f1 = (r.cum[P.k1] - r.cum[kA]) / span;
        list.push({ P: P, a: REV * f0, b: REV * f1 + 80 });
      }
      phase(list, 1, REV + 80);
      play(L.g, lt, pathFrames(r, 1.1, 1, kA, kB), { duration: REV, easing: "linear", fill: "both" });
      lifeLater(L, function () { lt.remove(); then(); }, REV + 100);
    }
    function goLive(L, ms) {
      var r = L.r, e = r.pts[r.pts.length - 1];
      L.phase = "live"; L.liveEnd = performance.now() + ms;
      L.loopEl = light(L.g.el, L.col);
      L.loop = play(L.g, L.loopEl, pathFrames(r, 0.9, 0.9), { duration: Math.max(3000, r.len / 0.2), iterations: Infinity, easing: "linear" });
      if (!L.ring) L.ring = play(L.g, light(L.g.el, L.col, "na-ring"), [{ transform: at(e[0], e[1]) + " scale(0.4)", opacity: 0.8 }, { transform: at(e[0], e[1]) + " scale(1.7)", opacity: 0 }],
        { duration: 2400, iterations: Infinity });
      lifeLater(L, function () { erase(L); }, ms);
    }
    function stopLoop(L) { if (L.loop) { L.loop.cancel(); L.loopEl.remove(); L.loop = null; } }
    function erase(L) {
      var r = L.r, ERASE = clamp(r.len / 0.38, 1400, 3600), lt = light(L.g.el, L.col);
      L.phase = "erase"; L.token++; stopLoop(L);
      phase(L.pieces.map(function (P) { return { P: P, a: ERASE * r.cum[P.k0] / r.len, b: ERASE * r.cum[P.k1] / r.len + 60 }; }), 0, ERASE + 60);
      play(L.g, lt, pathFrames(r, 0.9, 0.8), { duration: ERASE, easing: "linear", fill: "both" });
      lifeLater(L, function () {
        done(L.g); drop(lives, L); drop(used, L.r); mark(L.r, -1);
        later(function () { cycleRoute(L.slot); }, rnd(600, 2000));
      }, ERASE + 120);
    }
    // A detour from index kc of route r to its goal, around the obstacles, leaving
    // the kept part smoothly; its colours carry on from the joint.
    function detour(r, kc) {
      var p = r.pts[kc], s = nodeAt(p), g = nodeAt(r.pts[r.pts.length - 1]);
      if (obsMask[s] || obsMask[g]) return null;
      var path = astar(mapStep, s, g, 0.6);
      if (!path) return null;
      var poly = pull(path).map(nodePx), lead = [], k, j = kc;
      poly[0] = [p[0], p[1]];
      for (k = 2; k >= 1; k--) { while (j > 0 && r.cum[kc] - r.cum[j] < 40 * k) j--; lead.push(r.pts[j]); j = kc; }
      var tail = curveOf(poly, lead);
      if (!tail) return null;
      // A seamless joint: over its first 80 px the detour blends from the old
      // route's own course into the new one (same position and direction at the joint).
      var blend = [tail[0]], acc = 0, j2 = kc, BL = 80;
      for (k = 1; k < tail.length; k++) {
        acc += Math.hypot(tail[k][0] - tail[k - 1][0], tail[k][1] - tail[k - 1][1]);
        if (acc >= BL) { blend.push(tail[k]); continue; }
        while (j2 < r.pts.length - 1 && r.cum[j2] - r.cum[kc] < acc) j2++;
        var q = r.pts[j2], w = smooth(0, 1, acc / BL);
        blend.push([q[0] + (tail[k][0] - q[0]) * w, q[1] + (tail[k][1] - q[1]) * w]);
      }
      blend = resample(blend, 3);
      if (clear(blend)) tail = blend;
      var r2 = measured(r.pts.slice(0, kc + 1).concat(tail.slice(1))), f0 = frac(r, kc), base = r2.cum[kc], rest = Math.max(1, r2.len - base);
      r2.f = function (q) { return q <= kc ? frac(r, q) : f0 + (1 - f0) * (r2.cum[q] - base) / rest; };
      return r2;
    }
    // The blocked part of a living route dissolves from the joint onwards, a ping
    // marks the joint, and the detour appears behind a light, then the route lives on.
    function replan(L) {
      var r = L.r, ke = hitAt(r), pc = -1, i;
      if (L.phase !== "live" || ke < 0) return;
      for (i = 0; i < L.pieces.length; i++) if (r.cum[L.pieces[i].k0] <= r.cum[ke] - 110) pc = i;
      L.replanned = true;
      var kc = pc > 0 ? L.pieces[pc].k0 : -1, r2 = kc > 0 ? detour(r, kc) : null;
      if (!r2) { erase(L); return; }
      L.phase = "replan"; L.token++; stopLoop(L);
      var old = L.pieces.slice(pc), tc = tangent(r, kc), p = r.pts[kc], T = theme();
      phase(old.map(function (P, idx) { return { P: P, a: idx * 70, b: idx * 70 + 340 }; }), 0, old.length * 70 + 340);
      later(function () { old.forEach(function (P) { P.cv.remove(); }); }, old.length * 70 + 420);
      var ping = light(L.g.el, T.hot ? FROST : L.col, "na-ring");
      play(L.g, ping, [{ transform: at(p[0], p[1]) + " scale(0.3)", opacity: 1 }, { transform: at(p[0], p[1]) + " scale(2.4)", opacity: 0 }], { duration: 900, easing: "ease-out", fill: "both" });
      mark(r, -1); mark(r2, 1); drop(used, r); drop(pool, r); used.push(r2);
      L.r = r2; L.pieces = L.pieces.slice(0, pc).concat(buildPieces(L, r2, kc, r2.pts.length - 1, tc));
      lifeLater(L, function () {
        reveal(L, pc, function () { goLive(L, Math.max(3500, L.liveEnd - performance.now())); });
      }, 260);
    }
    function cycleRoute(slot) {
      if (!running()) { later(function () { cycleRoute(slot); }, 1500); return; }
      var r = pickRoute();
      if (!r) { later(function () { cycleRoute(slot); }, 700); return; }
      var P = theme().colors, L = { slot: slot, r: r, col: P[slot % P.length], g: Group(), pieces: [], token: 0, phase: "reveal", replanned: false };
      lives.push(L); used.push(r); mark(r, 1);
      L.pieces = buildPieces(L, r, 0, r.pts.length - 1, null);
      reveal(L, 0, function () { goLive(L, rnd(8000, 12000)); });
    }

    // ----------------------------------------------------------- lifecycle
    var destroyed = false, ro = null, io = null, rt = 0, lastW = 0, lastH = 0;
